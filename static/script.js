const updateInput = document.getElementById("updateInput");
const charCount = document.getElementById("charCount");


// ==========================================================
// CHARACTER COUNTER
// ==========================================================

updateInput.addEventListener("input", function () {

    const count = updateInput.value.length;

    charCount.textContent =
        `${count} character${count === 1 ? "" : "s"}`;

});


// ==========================================================
// ANALYZE UPDATE
// ==========================================================

async function analyzeUpdate() {

    const update = updateInput.value.trim();

    const button =
        document.getElementById("analyzeButton");

    const loading =
        document.getElementById("loading");

    const results =
        document.getElementById("results");

    const error =
        document.getElementById("error");


    // ------------------------------------------------------
    // VALIDATION
    // ------------------------------------------------------

    if (!update) {

        showError(
            "Please enter a project update."
        );

        updateInput.focus();

        return;
    }


    if (update.length > 5000) {

        showError(
            "Project update is too long. Please keep it under 5000 characters."
        );

        return;
    }


    // ------------------------------------------------------
    // RESET UI
    // ------------------------------------------------------

    error.classList.add("hidden");

    results.classList.add("hidden");

    loading.classList.remove("hidden");

    button.disabled = true;

    button.textContent = "Analyzing...";


    try {

        const response = await fetch(
            "/analyze",
            {
                method: "POST",

                headers: {
                    "Content-Type": "application/json"
                },

                body: JSON.stringify({
                    update: update
                })
            }
        );


        const data = await response.json();


        // --------------------------------------------------
        // SERVER ERROR
        // --------------------------------------------------

        if (!response.ok) {

            throw new Error(
                data.error ||
                "Unable to analyze update."
            );
        }


        // --------------------------------------------------
        // VERIFY GROQ AI
        // --------------------------------------------------

        if (data.analysis_mode !== "Groq AI") {

            throw new Error(
                "The response was not generated by Groq AI."
            );
        }


        // --------------------------------------------------
        // DISPLAY RESULTS
        // --------------------------------------------------

        displayResults(data);


    } catch (err) {

        console.error(
            "Analysis error:",
            err
        );

        showError(
            err.message ||
            "Something went wrong while analyzing the update."
        );


    } finally {

        loading.classList.add("hidden");

        button.disabled = false;

        button.textContent = "Analyze Update";

    }

}


// ==========================================================
// DISPLAY RESULTS
// ==========================================================

function displayResults(data) {

    const results =
        document.getElementById("results");


    results.classList.remove("hidden");


    // ======================================================
    // BASIC INFORMATION
    // ======================================================

    document.getElementById("employee").textContent =
        data.employee || "Not specified";


    document.getElementById("team").textContent =
        data.team || "Not specified";


    document.getElementById("status").textContent =
        data.status || "Not specified";


    document.getElementById("riskLevel").textContent =
        data.risk_level || "Not specified";


    // ======================================================
    // CONFIDENCE
    // ======================================================

    let confidence =
        Number(data.confidence);


    if (Number.isNaN(confidence)) {

        confidence = 0;

    }


    confidence =
        Math.max(
            0,
            Math.min(
                confidence,
                1
            )
        );


    document.getElementById("confidence").textContent =
        `${Math.round(confidence * 100)}%`;


    // ======================================================
    // VALIDATION
    // ======================================================

    const validationElement =
        document.getElementById("validation");


    if (data.clarification_needed) {

        validationElement.textContent =
            "Needs Clarification";

    } else {

        validationElement.textContent =
            "Validated";

    }


    // ======================================================
    // ANALYSIS MODE — GROQ AI ONLY
    // ======================================================

    const analysisMode =
        document.getElementById("analysisMode");

    const analysisModeContainer =
        document.querySelector(".analysis-mode");


    analysisMode.textContent =
        "Groq AI";


    // Remove all previous mode states.

    analysisModeContainer.classList.remove(
        "ai",
        "fallback"
    );


    // Always show Groq AI as the active mode.

    analysisModeContainer.classList.add(
        "ai"
    );


    // ======================================================
    // PROGRESS
    // ======================================================

    document.getElementById("progress").textContent =
        data.progress ||
        "Not specified";


    // ======================================================
    // NEXT STEP
    // ======================================================

    document.getElementById("nextStep").textContent =
        data.next_step ||
        "Not specified";


    // ======================================================
    // BLOCKERS
    // ======================================================

    renderList(
        "blockers",
        data.blockers,
        "No confirmed blockers."
    );


    // ======================================================
    // DEPENDENCIES
    // ======================================================

    renderList(
        "dependencies",
        data.dependencies,
        "No dependencies identified."
    );


    // ======================================================
    // MANAGER SUMMARY
    // ======================================================

    document.getElementById(
        "managerSummary"
    ).textContent =
        data.manager_summary ||
        "No summary available.";


    // ======================================================
    // CLARIFICATION
    // ======================================================

    const clarificationBox =
        document.getElementById(
            "clarificationBox"
        );


    const clarificationQuestion =
        document.getElementById(
            "clarificationQuestion"
        );


    if (data.clarification_needed) {

        clarificationBox.classList.remove(
            "hidden"
        );


        clarificationQuestion.textContent =
            data.clarification_question ||
            "Additional clarification is required.";

    } else {

        clarificationBox.classList.add(
            "hidden"
        );


        clarificationQuestion.textContent =
            "";

    }


    // ======================================================
    // STATUS VISUAL STATE
    // ======================================================

    applyStatusState(
        data.status
    );


    // ======================================================
    // RISK VISUAL STATE
    // ======================================================

    applyRiskState(
        data.risk_level
    );


    // ======================================================
    // SCROLL TO RESULTS
    // ======================================================

    results.scrollIntoView({
        behavior: "smooth",
        block: "start"
    });

}


// ==========================================================
// RENDER LIST
// ==========================================================

function renderList(
    elementId,
    items,
    emptyMessage
) {

    const element =
        document.getElementById(
            elementId
        );


    element.innerHTML = "";


    if (
        !Array.isArray(items) ||
        items.length === 0
    ) {

        const empty =
            document.createElement("div");


        empty.className =
            "empty";


        empty.textContent =
            emptyMessage;


        element.appendChild(
            empty
        );


        return;
    }


    items.forEach(function (item) {

        const div =
            document.createElement("div");


        div.className =
            "item";


        div.textContent =
            item;


        element.appendChild(
            div
        );

    });

}


// ==========================================================
// STATUS STATE
// ==========================================================

function applyStatusState(status) {

    const element =
        document.getElementById(
            "status"
        );


    element.classList.remove(
        "status-progress",
        "status-blocked",
        "status-investigating",
        "status-clarification",
        "status-completed"
    );


    switch (status) {

        case "Blocked":

            element.classList.add(
                "status-blocked"
            );

            break;


        case "Investigating":

            element.classList.add(
                "status-investigating"
            );

            break;


        case "Needs Clarification":

            element.classList.add(
                "status-clarification"
            );

            break;


        case "Completed":

            element.classList.add(
                "status-completed"
            );

            break;


        case "In Progress":

        default:

            element.classList.add(
                "status-progress"
            );

            break;

    }

}


// ==========================================================
// RISK STATE
// ==========================================================

function applyRiskState(riskLevel) {

    const element =
        document.getElementById(
            "riskLevel"
        );


    element.classList.remove(
        "risk-low",
        "risk-medium",
        "risk-high"
    );


    switch (riskLevel) {

        case "High":

            element.classList.add(
                "risk-high"
            );

            break;


        case "Medium":

            element.classList.add(
                "risk-medium"
            );

            break;


        case "Low":

        default:

            element.classList.add(
                "risk-low"
            );

            break;

    }

}


// ==========================================================
// ERROR MESSAGE
// ==========================================================

function showError(message) {

    const error =
        document.getElementById(
            "error"
        );


    error.textContent =
        message;


    error.classList.remove(
        "hidden"
    );

}